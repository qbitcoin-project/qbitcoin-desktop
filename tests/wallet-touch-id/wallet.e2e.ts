import { _electron as electron, expect, test } from '@playwright/test'
import { mkdirSync } from 'node:fs'
import { resolve } from 'node:path'
import { acceptPrivacy, focusedWindow } from '../e2e/privacyHelpers'

const phrase = 'abandon abandon abandon abandon abandon abandon abandon abandon abandon abandon abandon about'
const password = 'example-wallet-password'
function launch() {
  const profile = test.info().outputPath('account')
  mkdirSync(profile, { recursive: true })
  return electron.launch({ args: [resolve('test-results/wallet-touch-id-app/main/index.js'),
    '--use-mock-keychain', '--user-data-dir=' + profile], env: { ...process.env, WALLET_E2E_ROOT: profile } })
}

test('uses the native result for password fallback and requires verification to disable Touch ID', async () => {
  const app = await launch()
  try {
    const page = await focusedWindow(app)
    const button = (name: string) => page.getByRole('button', { name, exact: true })
    await button('I already have a wallet').click()
    await acceptPrivacy(page)
    await page.getByLabel('Recovery phrase').fill(phrase)
    await button('Continue').click()
    await page.getByLabel('Password', { exact: true }).fill(password)
    await page.getByLabel('Confirm password', { exact: true }).fill(password)
    await button('Restore wallet').click()
    await expect(button('Enable Touch ID')).toBeVisible()
    await expect(button('Lock wallet')).toHaveCount(0)
    await expect(page.getByRole('dialog')).toHaveCount(0)
    await button('Later').click()
    await button('Settings').click()
    await button('Set up Touch ID').click()
    await page.getByLabel('Wallet password').fill(password)
    await button('Enable Touch ID').click()
    await expect(button('Turn off Touch ID')).toBeVisible()
    await button('Lock wallet').click()
    await button('Unlock with Touch ID').click()
    await expect(button('Lock wallet')).toBeVisible()
    await button('Lock wallet').click()
    await app.evaluate(({ app }) => app.emit('test-wallet-cancel'))
    await button('Unlock with Touch ID').click()
    await expect(button('Unlock with Touch ID')).toBeEnabled()
    await expect(page.getByRole('alert')).toHaveCount(0)
    await app.evaluate(({ app }) => app.emit('test-wallet-final-attempt'))
    await button('Unlock with Touch ID').click()
    await expect(page.getByLabel('Password', { exact: true })).toBeFocused()
    await app.evaluate(({ app }) => app.emit('test-wallet-available'))
    await page.evaluate(() => window.dispatchEvent(new Event('focus')))
    await expect(button('Unlock with Touch ID')).toBeEnabled()
    const hint = await page.getByText('Use Touch ID to unlock this wallet.', { exact: true }).boundingBox()
    const primary = await button('Unlock with Touch ID').boundingBox()
    expect(primary!.y - hint!.y - hint!.height).toBeGreaterThanOrEqual(21)
    await app.evaluate(({ app }) => app.emit('test-wallet-deny'))
    await button('Unlock with Touch ID').click()
    await expect(page.getByLabel('Password', { exact: true })).toBeFocused()
    await expect(page.getByRole('alert')).toHaveCount(0)
    await page.getByLabel('Password', { exact: true }).fill(password)
    await button('Unlock').click()
    await button('Settings').click()
    await app.evaluate(({ app }) => app.emit('test-wallet-cancel'))
    await button('Turn off Touch ID').click()
    await expect(button('Turn off Touch ID')).toBeEnabled()
    await expect(page.getByRole('dialog')).toHaveCount(0)
    await app.evaluate(({ app }) => app.emit('test-wallet-deny'))
    await button('Turn off Touch ID').click()
    await expect(page.getByRole('alert')).toHaveText('Touch ID did not verify.')
    await expect(page.getByRole('dialog')).toHaveCount(0)
    await button('Turn off Touch ID').click()
    await expect(button('Set up Touch ID')).toBeVisible()
    await button('Lock wallet').click()
    await expect(page.getByLabel('Password', { exact: true })).toBeVisible()
    await expect(button('Unlock with Touch ID')).toHaveCount(0)
  } finally { await app.close() }
})

test('offers enrollment after backup and after password entry, before showing the wallet', async () => {
  const app = await launch()
  try {
    const page = await focusedWindow(app)
    const button = (name: string) => page.getByRole('button', { name, exact: true })
    await button('Create a new wallet').click()
    await page.getByLabel('Password', { exact: true }).fill(password)
    await page.getByLabel('Confirm password', { exact: true }).fill(password)
    await button('Continue').click()
    await acceptPrivacy(page)
    await expect(page.getByTestId('seed-word')).toHaveCount(12)
    const words = await page.getByTestId('seed-word').allTextContents()
    await page.getByRole('switch', { name: "I've saved these words somewhere safe" }).click()
    await button("I've written it down").click()
    const fields = page.locator('input[aria-label^="Word "]')
    await expect(fields).toHaveCount(3)
    for (const field of await fields.all()) {
      const label = await field.getAttribute('aria-label')
      await field.fill(words[Number(label?.slice('Word '.length)) - 1])
    }
    await button('Confirm').click()
    await expect(button('Enable Touch ID')).toBeVisible()
    await expect(button('Lock wallet')).toHaveCount(0)
    await app.evaluate(({ powerMonitor }) => powerMonitor.emit('lock-screen'))
    await page.getByLabel('Password', { exact: true }).fill(password)
    await button('Unlock').click()
    await expect(button('Enable Touch ID')).toBeVisible()
    await expect(page.locator('input[type="password"]')).toHaveCount(0)
    await expect(button('Lock wallet')).toHaveCount(0)
    await button('Enable Touch ID').click()
    await expect(button('Lock wallet')).toBeVisible()
    await button('Lock wallet').click()
    await button('Unlock with Touch ID').click()
    await expect(button('Lock wallet')).toBeVisible()
    await button('Settings').click()
    const lockoutHint = page.getByText('Touch ID is temporarily locked.', { exact: false })
    const refreshAvailability = () => page.evaluate(() => window.dispatchEvent(new Event('focus')))
    await app.evaluate(({ app }) => app.emit('test-wallet-lockout'))
    await refreshAvailability()
    await expect(lockoutHint).toBeVisible()
    await expect(button('Turn off Touch ID')).toBeEnabled()
    await expect(button('Set up Touch ID again')).toHaveCount(0)
    await button('Lock wallet').click()
    await expect(button('Unlock with Touch ID')).toHaveCount(0)
    await page.getByLabel('Password', { exact: true }).fill(password)
    await app.evaluate(({ app }) => app.emit('test-wallet-available'))
    await refreshAvailability()
    await expect(page.getByLabel('Password', { exact: true })).toHaveValue(password)
    await app.evaluate(({ app }) => app.emit('test-wallet-lockout'))
    await button('Unlock').click()
    await button('Settings').click()
    await expect(lockoutHint).toBeVisible()
    await app.evaluate(({ app }) => app.emit('test-wallet-unavailable'))
    await refreshAvailability()
    await expect(page.getByText('Touch ID is unavailable on this Mac.', { exact: false })).toBeVisible()
    await expect(lockoutHint).toHaveCount(0)
    await app.evaluate(({ app }) => app.emit('test-wallet-available'))
    await refreshAvailability()
    await expect(page.getByText('Touch ID is unavailable on this Mac.', { exact: false })).toHaveCount(0)
    await button('Lock wallet').click()
    await button('Unlock with Touch ID').click()
    await button('Settings').click()
    await app.evaluate(({ app }) => app.emit('test-wallet-new-enrollment'))
    await refreshAvailability()
    await button('Set up Touch ID again').click()
    const setup = page.getByRole('dialog', { name: 'Set up Touch ID again' })
    await setup.getByLabel('Wallet password').fill('wrong')
    await setup.getByRole('button', { name: 'Enable Touch ID' }).click()
    await expect(setup.getByRole('alert')).toBeVisible()
    await setup.getByLabel('Wallet password').fill(password)
    await setup.getByRole('button', { name: 'Enable Touch ID' }).click()
    await expect(setup).toHaveCount(0)
    await expect(button('Set up Touch ID again')).toHaveCount(0)
    await button('Lock wallet').click()
    await button('Unlock with Touch ID').click()
    await button('Settings').click()
    await app.evaluate(({ app }) => app.emit('test-wallet-lockout'))
    await button('Turn off Touch ID').click()
    const dialog = page.getByRole('dialog', { name: 'Turn off Touch ID' })
    await dialog.getByLabel('Wallet password').fill('incorrect')
    await dialog.getByRole('button', { name: 'Turn off Touch ID' }).click()
    await expect(dialog.getByRole('alert')).toBeVisible()
    await dialog.getByLabel('Wallet password').fill(password)
    await dialog.getByRole('button', { name: 'Turn off Touch ID' }).click()
    await expect(dialog).toHaveCount(0)
    await button('Lock wallet').click()
    await expect(page.getByLabel('Password', { exact: true })).toBeVisible()
  } finally { await app.close() }
})
